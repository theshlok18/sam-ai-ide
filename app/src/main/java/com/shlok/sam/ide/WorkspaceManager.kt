package com.shlok.sam.ide

import android.content.Context
import com.shlok.sam.data.model.Project
import com.shlok.sam.data.model.ProjectFile
import com.shlok.sam.data.model.ProjectType
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File

class WorkspaceManager(private val context: Context) {

    private val baseWorkspaceDir: File
        get() {
            val dir = File(context.filesDir, "sam_workspace")
            if (!dir.exists()) dir.mkdirs()
            return dir
        }

    suspend fun createProject(name: String, type: ProjectType, description: String = ""): Project = withContext(Dispatchers.IO) {
        val sanitized = name.trim().replace("\\s+".toRegex(), "_")
        val projectDir = File(baseWorkspaceDir, sanitized)
        if (!projectDir.exists()) projectDir.mkdirs()

        // Generate starter template based on type
        when (type) {
            ProjectType.KOTLIN_ANDROID -> generateKotlinAndroidTemplate(projectDir, name)
            ProjectType.PYTHON_FASTAPI -> generatePythonTemplate(projectDir, name)
            ProjectType.REACT_NATIVE -> generateReactNativeTemplate(projectDir, name)
            ProjectType.WEB_VITE -> generateWebViteTemplate(projectDir, name)
            ProjectType.RUST -> generateRustTemplate(projectDir, name)
        }

        val filesCount = countFiles(projectDir)

        Project(
            name = name,
            description = description,
            projectType = type,
            rootPath = projectDir.absolutePath,
            filesCount = filesCount,
            tags = when (type) {
                ProjectType.KOTLIN_ANDROID -> "Android, Kotlin, Jetpack Compose"
                ProjectType.PYTHON_FASTAPI -> "Backend, Python, FastAPI"
                ProjectType.REACT_NATIVE -> "Mobile, Cross-Platform, TS"
                ProjectType.WEB_VITE -> "Web, Vite, TypeScript"
                ProjectType.RUST -> "Systems, Rust, Cargo"
            }
        )
    }

    suspend fun getFileTree(projectRootPath: String): List<ProjectFile> = withContext(Dispatchers.IO) {
        val rootDir = File(projectRootPath)
        if (!rootDir.exists() || !rootDir.isDirectory) return@withContext emptyList()
        scanDirectory(rootDir)
    }

    private fun scanDirectory(dir: File): List<ProjectFile> {
        val list = mutableListOf<ProjectFile>()
        val files = dir.listFiles()?.sortedWith(compareBy({ !it.isDirectory }, { it.name })) ?: return emptyList()

        for (file in files) {
            if (file.isDirectory) {
                list.add(
                    ProjectFile(
                        name = file.name,
                        path = file.absolutePath,
                        isDirectory = true,
                        children = scanDirectory(file)
                    )
                )
            } else {
                list.add(
                    ProjectFile(
                        name = file.name,
                        path = file.absolutePath,
                        isDirectory = false,
                        size = file.length(),
                        extension = file.extension
                    )
                )
            }
        }
        return list
    }

    suspend fun readFileContent(filePath: String): String = withContext(Dispatchers.IO) {
        val file = File(filePath)
        if (file.exists() && file.isFile) {
            file.readText()
        } else {
            ""
        }
    }

    suspend fun saveFileContent(filePath: String, content: String) = withContext(Dispatchers.IO) {
        val file = File(filePath)
        file.parentFile?.mkdirs()
        file.writeText(content)
    }

    private fun countFiles(dir: File): Int {
        var count = 0
        dir.walkTopDown().forEach { if (it.isFile) count++ }
        return count
    }

    private fun generateKotlinAndroidTemplate(dir: File, name: String) {
        val mainKt = File(dir, "MainActivity.kt")
        mainKt.writeText(
            """package com.shlok.app

import android.os.Bundle
import androidx.activity.ComponentActivity
import androidx.activity.compose.setContent
import androidx.compose.material3.*
import androidx.compose.runtime.*

class MainActivity : ComponentActivity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        setContent {
            MaterialTheme {
                Surface {
                    Text("Welcome to $name generated by S.A.M.")
                }
            }
        }
    }
}
""".trimIndent()
        )

        val buildGradle = File(dir, "build.gradle.kts")
        buildGradle.writeText(
            """plugins {
    alias(libs.plugins.android.application)
    alias(libs.plugins.kotlin.android)
}

android {
    namespace = "com.shlok.$name"
    compileSdk = 35
}
""".trimIndent()
        )
    }

    private fun generatePythonTemplate(dir: File, name: String) {
        val mainPy = File(dir, "main.py")
        mainPy.writeText(
            """from fastapi import FastAPI

app = FastAPI(title="$name", description="Built with S.A.M. Autonomous IDE")

@app.get("/")
def read_root():
    return {"message": "Hello from $name API", "architect": "Shlok", "status": "online"}
""".trimIndent()
        )

        val reqs = File(dir, "requirements.txt")
        reqs.writeText("fastapi>=0.110.0\nuvicorn>=0.28.0\npydantic>=2.6.0\n")
    }

    private fun generateReactNativeTemplate(dir: File, name: String) {
        val appTsx = File(dir, "App.tsx")
        appTsx.writeText(
            """import React from 'react';
import { StyleSheet, Text, View } from 'react-native';

export default function App() {
  return (
    <View style={styles.container}>
      <Text style={styles.title}>$name</Text>
      <Text style={styles.subtitle}>Powered by S.A.M. Neural Core</Text>
    </View>
  );
}

const styles = StyleSheet.create({
  container: { flex: 1, backgroundColor: '#07090E', alignItems: 'center', justifyContent: 'center' },
  title: { color: '#5685FF', fontSize: 24, fontWeight: 'bold' },
  subtitle: { color: '#8D909F', marginTop: 8 }
});
""".trimIndent()
        )
    }

    private fun generateWebViteTemplate(dir: File, name: String) {
        val indexHtml = File(dir, "index.html")
        indexHtml.writeText(
            """<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <title>$name // S.A.M. Web</title>
</head>
<body style="background:#07090E;color:#E2E2E9;font-family:sans-serif;padding:2rem;">
  <h1>$name</h1>
  <p>Autonomous Web Workspace running.</p>
</body>
</html>
""".trimIndent()
        )
    }

    private fun generateRustTemplate(dir: File, name: String) {
        val mainRs = File(dir, "main.rs")
        mainRs.writeText(
            """fn main() {
    println!("S.A.M. High-Performance Core: $name initialized!");
}
""".trimIndent()
        )
    }
}
